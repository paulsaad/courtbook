#!/usr/bin/env bash
# Generates supabase/live/pkg1_apply.sql — Package 1 for LIVE (0067 + 0072 + 0073) as ONE transaction.
# It is assembled mechanically from the verified pieces, nothing rewritten:
#   0067: the guarded body of 0067_apply.sql (its start check, the migration unchanged, its result check)
#   0072: the guarded body of 0072_apply.sql (same)
#   0073: the migration unchanged, between a start check (= 0073_preflight.sql part 1) and a result
#         check (= 0073_postcheck.sql)
# Any failed check raises, and the whole package is rolled back: all three or none.
#   bash supabase/live/make_package1.sh      (OUT=<dir> writes elsewhere, for the sync check)
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=${OUT:-supabase/live}
body() {  # the lines of an NNNN_apply.sql between its "set local" lines and its notify/commit
  awk '/^set local statement_timeout/ {on=1; next} /^notify pgrst/ {on=0} on' "$1"
}
H="md5(regexp_replace(prosrc, '[ \\t\\r]+(\\n|\$)', '\\1', 'g'))"
{
  echo "-- Package 1 for LIVE, all or nothing: 0067 (game detail) + 0072 (game hardening) + 0073 (post key)."
  echo "-- Run once in Supabase → SQL Editor: first pkg1_preflight.sql (part 1 all ok), then this, then pkg1_postcheck.sql."
  echo "-- Generated by supabase/live/make_package1.sh from 0067_apply.sql, 0072_apply.sql and"
  echo "-- supabase/migrations/0073_post_match_token.sql — do not edit by hand."
  echo "begin;"
  echo "set local lock_timeout = '5s';"
  echo "set local statement_timeout = '60s';"
  echo "-- ######## 0067 ########"
  body supabase/live/0067_apply.sql
  echo "-- ######## 0072 ########"
  body supabase/live/0072_apply.sql
  echo "-- ######## 0073 ########"
  cat <<SQL
do \$pre\$ begin
  if not (exists (select 1 from pg_proc where pronamespace = 'public'::regnamespace and proname = 'resolve_court')
      and (select count(*) = 1 and max($H) = '33b26aae02b8861858f86de235b66264' from pg_proc where pronamespace = 'public'::regnamespace and proname = 'post_match')
      and not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'matches' and column_name = 'client_token')
      and not exists (select 1 from pg_indexes where indexname = 'matches_organizer_client_token')) then
    raise exception 'STOPPED, nothing changed: not the verified 0072 starting point for 0073';
  end if;
end \$pre\$;
SQL
  echo "-- ===== migration 0073, unchanged from supabase/migrations/0073_post_match_token.sql ====="
  cat supabase/migrations/0073_post_match_token.sql
  echo "-- ===== end of migration 0073 ====="
  cat <<SQL
do \$post\$ begin
  if not ((select count(*) = 1 and max($H) = '6a8feb9a5b8c59e81d8d72ac49076635' from pg_proc where pronamespace = 'public'::regnamespace and proname = 'post_match')
      and (select pg_get_function_arguments(oid) like '%p_join_mode text DEFAULT ''open''::text, p_token uuid DEFAULT NULL::uuid' from pg_proc where pronamespace = 'public'::regnamespace and proname = 'post_match')
      and has_function_privilege('authenticated', 'post_match(uuid,sport,timestamptz,timestamptz,int,int,int,text,uuid,text,uuid)', 'execute')
      and has_function_privilege('service_role', 'post_match(uuid,sport,timestamptz,timestamptz,int,int,int,text,uuid,text,uuid)', 'execute')
      and not has_function_privilege('anon', 'post_match(uuid,sport,timestamptz,timestamptz,int,int,int,text,uuid,text,uuid)', 'execute')
      and exists (select 1 from pg_indexes where indexname = 'matches_organizer_client_token' and indexdef like '%UNIQUE%(organizer_id, client_token)%')) then
    raise exception 'ROLLED BACK: the result of 0073 is not the verified version';
  end if;
end \$post\$;
SQL
  echo "notify pgrst, 'reload schema';"
  echo "commit;"
  echo "select 'package 1 applied: 0067, 0072, 0073' as result;"
} > "$OUT/pkg1_apply.sql"
