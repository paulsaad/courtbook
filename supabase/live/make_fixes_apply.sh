#!/usr/bin/env bash
# Generates supabase/live/00{68,69,70,71}_apply.sql: each is ONE transaction for the SQL Editor that
#   1. stops, changing nothing, unless the objects it replaces are exactly the verified 0001–0066 versions
#   2. runs the migration file unchanged (copied byte for byte between the markers)
#   3. rolls everything back unless the result is exactly the verified new version
# A second run stops at step 1. Regenerate after any change to a migration:
#   bash supabase/live/make_fixes_apply.sh          (OUT=<dir> writes elsewhere, for the sync check)
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=${OUT:-supabase/live}
H='md5(regexp_replace(prosrc, '"'"'[ \t\r]+(\n|$)'"'"', '"'"'\1'"'"', '"'"'g'"'"'))'
fnh() { echo "(select count(*) = 1 and max($H) = '$2' from pg_proc where pronamespace = 'public'::regnamespace and proname = '$1')"; }

gen() { # number, title, pre-condition SQL, post-condition SQL, extra-before, extra-after
  local n=$1 f; f=$(ls supabase/migrations/${n}_*.sql)
  {
    echo "-- $n for staging or LIVE, all or nothing: $2"
    echo "-- Run once in Supabase → SQL Editor AFTER supabase/live/fixes_preflight.sql showed every part 1-2 row ok."
    echo "-- Generated by supabase/live/make_fixes_apply.sh from $f — do not edit by hand."
    echo "begin;"
    echo "set local lock_timeout = '5s';"
    echo "set local statement_timeout = '60s';"
    echo "do \$pre\$ begin"
    echo "  if not ($3) then"
    echo "    raise exception 'STOPPED, nothing changed: the objects $n replaces are not the verified 0001–0066 versions (already applied?)';"
    echo "  end if;"
    echo "end \$pre\$;"
    [ -n "${5:-}" ] && echo "$5"
    echo "-- ===== migration $n, unchanged from $f ====="
    cat "$f"
    echo "-- ===== end of migration $n ====="
    echo "do \$post\$ begin"
    echo "  if not ($4) then"
    echo "    raise exception 'ROLLED BACK: the result of $n is not the verified version';"
    echo "  end if;"
    echo "end \$post\$;"
    echo "notify pgrst, 'reload schema';"
    echo "commit;"
    if [ -n "${6:-}" ]; then echo "$6"; else echo "select '$n applied' as result;"; fi
  } > "$OUT/${n}_apply.sql"
  echo "wrote $OUT/${n}_apply.sql"
}

gen 0068 "club blocks readable by that club's staff and admins only (R2)" \
  "exists (select 1 from pg_policies where tablename = 'blocks' and policyname = 'blocks: read' and qual = 'true')
      and not exists (select 1 from pg_policies where tablename = 'blocks' and policyname = 'blocks: staff read')" \
  "not exists (select 1 from pg_policies where tablename = 'blocks' and policyname = 'blocks: read')
      and (select string_agg(policyname, ',' order by policyname) from pg_policies where tablename = 'blocks' and cmd in ('SELECT', 'ALL')) = 'blocks: staff read,blocks: staff write'
      and exists (select 1 from pg_policies where tablename = 'blocks' and policyname = 'blocks: staff read' and qual = 'is_staff_of(club_id)')"

gen 0069 "no direct delete of a game (S1); notices: only read_at writable (S5)" \
  "exists (select 1 from pg_policies where tablename = 'matches' and policyname = 'matches: organizer delete')
      and exists (select 1 from information_schema.column_privileges where table_schema = 'public' and table_name = 'notifications' and grantee = 'authenticated' and privilege_type = 'UPDATE' and column_name <> 'read_at')" \
  "not exists (select 1 from pg_policies where tablename = 'matches' and cmd = 'DELETE')
      and not has_table_privilege('authenticated', 'public.matches', 'DELETE') and not has_table_privilege('anon', 'public.matches', 'DELETE')
      and (select string_agg(column_name, ',') from information_schema.column_privileges where table_schema = 'public' and table_name = 'notifications' and grantee = 'authenticated' and privilege_type = 'UPDATE') = 'read_at'
      and has_table_privilege('service_role', 'public.notifications', 'UPDATE')"

gen 0070 "simulated payment only at demo clubs; new clubs at the desk (D1)" \
  "(select column_default from information_schema.columns where table_schema = 'public' and table_name = 'clubs' and column_name = 'payment_mode') = '''simulated''::text'
      and not exists (select 1 from pg_constraint where conname = 'clubs_simulated_only_demo')
      and $(fnh set_club_payment_mode ffd87dcbedbf00607c15639123eb1629)" \
  "(select column_default from information_schema.columns where table_schema = 'public' and table_name = 'clubs' and column_name = 'payment_mode') = '''at_desk''::text'
      and exists (select 1 from pg_constraint where conname = 'clubs_simulated_only_demo' and convalidated)
      and not exists (select 1 from clubs where payment_mode = 'simulated' and not is_demo)
      and $(fnh set_club_payment_mode 0af6719940f8fcfe481ad47181e09f39)
      and has_function_privilege('authenticated', 'public.set_club_payment_mode(uuid, text)', 'execute')
      and not has_function_privilege('anon', 'public.set_club_payment_mode(uuid, text)', 'execute')" \
  "-- the SQL Editor may not show NOTICEs: remember which clubs 0070 switches, and show them at the end
create temp table fix0070_switched on commit preserve rows as
  select c.slug, (select count(*) from bookings b where b.club_id = c.id and b.status = 'pending') as holds_released
  from clubs c where c.payment_mode = 'simulated' and not c.is_demo;" \
  "select '0070 applied' as result, coalesce((select string_agg(slug || ' (' || holds_released || ' hold(s) released)', ', ') from fix0070_switched), 'no club switched') as switched_to_the_desk;"

