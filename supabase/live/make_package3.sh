#!/usr/bin/env bash
# Generates supabase/live/pkg3_apply.sql — Package 3 for LIVE (0074 + 0075) as ONE transaction.
# Assembled mechanically, nothing rewritten: each migration file runs unchanged between its own verified
# checks, embedded verbatim as subqueries:
#   before 0074: every part-1 row of 0074_preflight.sql true     after 0074: every row of 0074_postcheck.sql true
#   before 0075: every row of 0075_preflight.sql true            after 0075: every row of 0075_postcheck.sql true
# Any failed check raises, and the whole package is rolled back: both or none.
#   bash supabase/live/make_package3.sh      (OUT=<dir> writes elsewhere, for the sync check)
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=${OUT:-supabase/live}
q() { grep -v '^\s*--' "supabase/live/$1.sql" | sed -e '$ s/;\s*$//'; }   # the query, without comment lines or final ;
guard() {  # $1 tag, $2 check file, $3 extra condition, $4 message
  echo "do \$$1\$ begin"
  echo "  if exists (select 1 from ("
  q "$2"
  echo "  ) chk where $3 not ok) then"
  echo "    raise exception '$4';"
  echo "  end if;"
  echo "end \$$1\$;"
}
{
  echo "-- Package 3 for LIVE, all or nothing: 0074 (chat and player safety) + 0075 (moderator history)."
  echo "-- Run once in Supabase → SQL Editor: first pkg3_preflight.sql (part 1 all ok), then this, then pkg3_postcheck.sql."
  echo "-- Generated by supabase/live/make_package3.sh from the 0074/0075 migrations and their preflight and"
  echo "-- postcheck scripts — do not edit by hand."
  echo "begin;"
  echo "set local lock_timeout = '5s';"
  echo "set local statement_timeout = '60s';"
  echo "-- ######## 0074 ########"
  guard pre74 0074_preflight "part = 1 and" "STOPPED, nothing changed: not the verified 0073 starting point for 0074 (0074 already applied?)"
  echo "-- ===== migration 0074, unchanged from supabase/migrations/0074_safety.sql ====="
  cat supabase/migrations/0074_safety.sql
  echo "-- ===== end of migration 0074 ====="
  guard post74 0074_postcheck "" "ROLLED BACK: the result of 0074 is not the verified version"
  echo "-- ######## 0075 ########"
  guard pre75 0075_preflight "" "STOPPED, nothing changed: not the verified 0074 starting point for 0075"
  echo "-- ===== migration 0075, unchanged from supabase/migrations/0075_report_history.sql ====="
  cat supabase/migrations/0075_report_history.sql
  echo "-- ===== end of migration 0075 ====="
  guard post75 0075_postcheck "" "ROLLED BACK: the result of 0075 is not the verified version"
  echo "notify pgrst, 'reload schema';"
  echo "commit;"
  echo "select 'package 3 applied: 0074, 0075' as result;"
} > "$OUT/pkg3_apply.sql"
