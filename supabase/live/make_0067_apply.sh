#!/usr/bin/env bash
# Generates supabase/live/0067_apply.sql for the SQL Editor (live) — ONE transaction that
#   1. stops, changing nothing, unless the starting point is exactly 0001–0071 without 0067
#   2. runs supabase/migrations/0067_match_detail.sql unchanged (copied byte for byte)
#   3. rolls everything back unless the result is exactly the verified 0067
# A second run stops at step 1. On staging, 0067 goes through the workflow's apply action instead
# (migrations: 0067), between the m3_0067_preflight and m3_0067_postcheck actions.
#   bash supabase/live/make_0067_apply.sh      (OUT=<dir> writes elsewhere, for the sync check)
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=${OUT:-supabase/live}
f=supabase/migrations/0067_match_detail.sql
{
  echo "-- 0067 for LIVE, all or nothing: match_detail (game detail for the app; web game page after start)."
  echo "-- Run once in Supabase → SQL Editor: first 0067_preflight.sql (part 1 all ok), then this, then 0067_postcheck.sql."
  echo "-- Generated by supabase/live/make_0067_apply.sh from $f — do not edit by hand."
  echo "begin;"
  echo "set local lock_timeout = '5s';"
  echo "set local statement_timeout = '60s';"
  echo "do \$pre\$ begin"
  echo "  if not ((select pg_get_constraintdef(oid) from pg_constraint where conname = 'matches_closed_reason_check')"
  echo "        = 'CHECK ((closed_reason = ANY (ARRAY[''full''::text, ''organizer''::text])))'"
  echo "      and not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'matches' and column_name = 'court_lost_at')"
  echo "      and not exists (select 1 from pg_proc where pronamespace = 'public'::regnamespace and proname = 'match_detail')"
  echo "      and exists (select 1 from pg_constraint where conname = 'clubs_simulated_only_demo')) then"
  echo "    raise exception 'STOPPED, nothing changed: not the verified 0001–0071 starting point (0067 already applied, or release fixes missing?)';"
  echo "  end if;"
  echo "end \$pre\$;"
  echo "-- ===== migration 0067, unchanged from $f ====="
  cat "$f"
  echo "-- ===== end of migration 0067 ====="
  echo "do \$post\$ begin"
  echo "  if not ((select pg_get_constraintdef(oid) from pg_constraint where conname = 'matches_closed_reason_check')"
  echo "        = 'CHECK ((closed_reason = ANY (ARRAY[''full''::text, ''organizer''::text, ''no_court''::text])))'"
  echo "      and exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'matches' and column_name = 'court_lost_at' and is_nullable = 'YES')"
  echo "      and (select count(*) = 1 and max(md5(regexp_replace(prosrc, '[ \\t\\r]+(\\n|\$)', '\\1', 'g'))) = 'bc1682b6c836fdae0b82a5d4a3463c7a' from pg_proc where pronamespace = 'public'::regnamespace and proname = 'match_detail')"
  echo "      and has_function_privilege('authenticated', 'public.match_detail(uuid)', 'execute')"
  echo "      and not has_function_privilege('anon', 'public.match_detail(uuid)', 'execute')) then"
  echo "    raise exception 'ROLLED BACK: the result of 0067 is not the verified version';"
  echo "  end if;"
  echo "end \$post\$;"
  echo "notify pgrst, 'reload schema';"
  echo "commit;"
  echo "select '0067 applied' as result;"
} > "$OUT/0067_apply.sql"
echo "wrote $OUT/0067_apply.sql"
