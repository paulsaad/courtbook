#!/usr/bin/env python3
"""Ports supabase/tests/m2/deletion_races.sh (0079) to 0086 as supabase/tests/m86/ported_deletion_races.sh.
Named edits only; every other line runs as written. Run: python3 supabase/tests/m86/port_0079_races.py"""
import pathlib, sys
root = pathlib.Path(__file__).resolve().parents[3]
src = (root / "supabase/tests/m2/deletion_races.sh").read_text()
edits = [
  # the copy gets its own database name
  ("SRC=courtbook_test; DB=courtbook_m2_race", "SRC=courtbook_test; DB=courtbook_m86_race_0079"),
  # RD5: under 0086 a closed account cannot write at all (D1, lock-out). The person's own cancellation is refused with
  # account_closed and the deletion cancels both bookings under the club's rules. 0079 let it through.
  ('''echo "== RD5 the person cancels their own booking while the deletion starts"
setup
race "$P" "select cancel_booking('$B1')" "$A" "$DEL"
common RD5
rep "RD5: their own cancellation stands with the normal refund; the deletion cancelled the other" \\
    "$([ "$(q "select status from payments where booking_id = '$B1'")" = refund_due ] \\
       && [ "$(q "select summary->>'bookings_cancelled' from account_deletions where subject_id = '$P'")" = 1 ] && echo true)" \\
    "$(q "select status || ' ' || coalesce(note, '') from payments where booking_id = '$B1'")"''',
   '''echo "== RD5 (0086) the closed person tries to cancel their own booking while the deletion starts"
setup
race "$P" "select cancel_booking('$B1')" "$A" "$DEL"
rep "RD5: no deadlock; their cancellation is refused (account_closed), the deletion succeeds" \\
    "$(nodead && [ "$(cat $W/a.rc)" != 0 ] && grep -q account_closed $W/a.out && [ "$(cat $W/b.rc)" = 0 ] && echo true)" "A rc $(cat $W/a.rc): $(tail -1 $W/a.out | cut -c1-120) / B rc $(cat $W/b.rc)"
rep "RD5: no upcoming or pending booking left for an anonymised owner, none left under their name" \\
    "$([ "$(q "$ACTIVE_ANON")" = 0 ] && [ "$(q "$LEFT_NAMED")" = 0 ] && echo true)" "active anon $(q "$ACTIVE_ANON"), named $(q "$LEFT_NAMED")"
rep "RD5: the deletion cancelled both, each with the refund the club's rules give" \\
    "$([ "$(q "select summary->>'bookings_cancelled' from account_deletions where subject_id = '$P'")" = 2 ] \\
       && [ "$(q "select count(*) from payments where booking_id in ('$B1', '$B2') and status = 'refund_due'")" = 2 ] && echo true)" \\
    "$(q "select summary::text from account_deletions where subject_id = '$P'") / $(q "select string_agg(status::text, ',') from payments where booking_id in ('$B1', '$B2')")"'''),
]
out = src
for old, new in edits:
    if out.count(old) != 1: sys.exit(f"edit not found exactly once: {old[:70]!r}")
    out = out.replace(old, new)
header = "# GENERATED by supabase/tests/m86/port_0079_races.py from supabase/tests/m2/deletion_races.sh (0079). Do not edit by hand.\n"
lines = out.split("\n", 1)
(root / "supabase/tests/m86/ported_deletion_races.sh").write_text(lines[0] + "\n" + header + lines[1])
print("ported:", len(edits), "edits")
